def generate_course_levels(start_date: datetime, course_ids: list[int]) -> Dict:
    if len(course_ids) != 5:
        raise ValueError("Expected 5 unlock challenge course IDs")

    # unlock challenge progression
    # - day 1: 10 life master (or ultima if exists)
    # - day 4: 50 life master
    # - day 7: 150 life expert
    # - day 14: 150 life advanced
    # - day 21: 150 life basic
    start_date = start_date.replace(hour=7, minute=0, second=0, microsecond=0)
    deltas = [0, 3, 3, 7, 7]
    current_date = datetime.utcnow()

    for i, course_id in enumerate(course_ids):
        period_start_date = start_date + timedelta(days=sum(deltas[0 : i + 1]))

        if i < 4:
            period_end_date = start_date + timedelta(days=sum(deltas[0 : i + 2]))
        else:
            period_end_date = datetime(2099, 12, 31, 23, 59, 59)

        if period_start_date <= current_date and current_date <= period_end_date:
            return {
                "courseId": course_id,
                "startDate": period_start_date.strftime("%Y-%m-%d %H:%M:%S"),
                "endDate": period_end_date.strftime("%Y-%m-%d %H:%M:%S"),
            }

    return {
        "courseId": course_ids[-1],
        "startDate": start_date.strftime("%Y-%m-%d %H:%M:%S"),
        "endDate": "2099-12-31 23:59:59",
    }


def add_always_unlocked_unlock_challenge(
    events_by_id: dict[int, Any],
    conditions: list[dict[str, Any]],
    event_id: int,
    unlock_challenge_id: int,
    date_time_format: str = "%Y-%m-%d %H:%M:%S",
):
    if event := events_by_id.get(event_id):
        conditions.append(
            {
                "unlockChallengeId": unlock_challenge_id,
                "length": 1,
                "conditionList": [
                    {
                        # By default, unlock challenges are only unlocked for players with
                        # 5.00 rating or above.
                        "type": MapAreaConditionType.MINIMUM_RATING.value,
                        "conditionId": 500,
                        "logicalOpe": MapAreaConditionLogicalOperator.AND.value,
                        "startDate": event["startDate"].strftime(date_time_format),
                        "endDate": "2099-12-31 00:00:00",
                    }
                ],
            }
        )


